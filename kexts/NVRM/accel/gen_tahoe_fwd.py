#!/usr/bin/env python3
"""gen_tahoe_fwd.py NVACCEL_BINARY MISSING_SYMBOLS — writes tahoe_fwd.h for the macOS 26 build.

Tahoe (26) made 27 IOAcceleratorFamily2 methods private and retyped 7 more (unsigned int -> enum), so a kext can no longer
link to them by name. NVAccel never calls them: they only fill vtable slots our classes inherit. The vtable layout itself
is unchanged (every base vtable has the same slot count and order as on macOS 15; checked with tools/vtdump.py against the
26.7.1 KDK), and Apple still exports every base vtable. So for the 26 build each such slot gets an override that jumps
through the base class's exported vtable, which reaches Apple's implementation without naming it."""
import re, subprocess, sys, os, pathlib, tempfile
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', 'tools'))
from vtdump import vtables
HERE = os.path.dirname(os.path.abspath(__file__))
BASES = {'NVResource': 'IOAccelResource2', 'NVSysMemory': 'IOAccelSysMemory', 'NVVidMemory': 'IOAccelVidMemory',
         'NVSurface': 'IOAccelLegacySurface', 'NVDisplayPipe': 'IOAccelLegacyDisplayPipe', 'NVGLContext': 'IOAccelGLContext2',
         'NV2DContext': 'IOAccel2DContext2', 'NVCLContext': 'IOAccelCLContext2', 'NVVideoContext': 'IOAccelVideoContext2',
         'NVEventMachine': 'IOAccelEventMachineFast2', 'NVDisplayMachine': 'IOAccelLegacyDisplayMachine', 'NVTask': 'IOAccelTask',
         'NVMemoryMap': 'IOAccelMemoryMap', 'NVAccel': 'IOGraphicsAccelerator2'}
def split_types(text):
    """Split only top-level commas (template and function types may contain them)."""
    if not text.strip() or text.strip() == 'void':
        return []
    args = []; start = 0; stack = []
    pairs = {')': '(', ']': '[', '>': '<'}
    for i, char in enumerate(text):
        if char in '([<': stack.append(char)
        elif char in ')]>':
            if not stack or stack.pop() != pairs[char]:
                raise ValueError('unbalanced parameter type: ' + text)
        elif char == ',' and not stack:
            args.append(text[start:i].strip()); start = i + 1
    if stack:
        raise ValueError('unbalanced parameter type: ' + text)
    args.append(text[start:].strip())
    if any(not arg for arg in args):
        raise ValueError('empty parameter type: ' + text)
    return args

def normalized_type(text):
    text = re.sub(r'\s+', ' ', text.strip())
    return re.sub(r'\s*([*&<>,()\[\]])\s*', r'\1', text)

def signature(owner, name, args, const):
    return owner, name, tuple(normalized_type(arg) for arg in args), const

def decls():
    out = {}
    for sub in ('iofam', 're'):
      for f in sorted(os.listdir(os.path.join(HERE, sub))):
        if not f.endswith('.h'): continue
        cls = f[:-2]
        text = pathlib.Path(HERE, sub, f).read_text(encoding='utf-8')
        text = re.sub(r'/\*.*?\*/|//[^\n]*', '', text, flags=re.S)
        for m in re.finditer(r'\bvirtual\s+([^;{}]+?)\s+([A-Za-z_]\w*)\((.*?)\)(\s*const)?\s*(?:=\s*0)?\s*(?:APPLE_KEXT_OVERRIDE)?\s*;', text, re.S):
            args = [' '.join(arg.split()) for arg in split_types(m.group(3))]
            key = signature(cls, m.group(2), args, bool(m.group(4)))
            value = (' '.join(m.group(1).split()), args)
            if key in out and out[key] != value:
                raise ValueError('conflicting declarations for ' + str(key))
            out[key] = value
    return out
def main(binary, missfile):
    miss = {l.strip() for l in pathlib.Path(missfile).read_text(encoding='utf-8').splitlines() if l.strip()}
    if not miss:
        raise ValueError('missing-symbol list is empty; refusing to replace the header')
    vt = vtables(binary); d = decls()
    result = subprocess.run(['c++filt'], input='\n'.join(sorted(miss)) + '\n', capture_output=True, text=True)
    if result.returncode:
        raise ValueError('c++filt failed: ' + result.stderr.strip())
    lines = result.stdout.splitlines()
    if len(lines) != len(miss):
        raise ValueError('c++filt did not return one name per missing symbol')
    demangled = dict(zip(sorted(miss), lines))
    h = ['// GENERATED by gen_tahoe_fwd.py for the macOS 26 (Tahoe) build. Do not edit.', '#pragma once', '#ifdef NM_TAHOE']
    defs = []; used = set(); handled = set(); n = 0
    for cls, base in BASES.items():
        key = '%d%s' % (len(cls), cls)
        if key not in vt:
            raise ValueError('missing derived vtable: ' + cls)
        slots = vt[key]
        decl_lines = []
        declared = set()
        for idx, sym in enumerate(slots):
            if sym not in miss: continue
            dn = demangled[sym]
            m = re.match(r'(\w+)::(\w+)\((.*)\)( const)?$', dn)
            if not m:
                raise ValueError('cannot parse missing method: ' + dn)
            owner, name, const = m.group(1), m.group(2), bool(m.group(4))
            key = signature(owner, name, split_types(m.group(3)), const)
            if key not in d:
                raise ValueError('no exact header declaration for ' + dn)
            if key in declared:
                raise ValueError('duplicate forwarding slot for ' + dn)
            declared.add(key)
            ret, args = d[key]; arity = len(args)
            params = ', '.join('%s a%d' % (a, i) for i, a in enumerate(args))
            types = ''.join(', ' + a for a in args); call = ''.join(', a%d' % i for i in range(arity))
            c = ' const' if const else ''
            decl_lines.append('    %s %s(%s)%s override;' % (ret, name, params, c))
            # The vtable address is loaded through the GOT: ld -kext leaves a RIP-relative lea to an undefined symbol with no
            # relocation at all (measured: it pointed at 0), while GOT entries get UNSIGNED relocations the kernel linker fills.
            # A naked tail jump through the base vtable slot: every argument and return register passes through untouched,
            # so the reconstructed headers' return types (several are only known as void) cannot truncate a result.
            defs.append('__attribute__((naked)) %s %s::%s(%s)%s { __asm__("movq __ZTV%d%s@GOTPCREL(%%rip), %%r11\\n\\tjmpq *%d(%%r11)"); }'
                        % (ret, cls, name, params, c, len(base), base, 8 * (2 + idx)))
            used.add(base); handled.add(sym); n += 1
        h.append('#define NM_TAHOE_FWD_%s \\\n%s' % (cls, ' \\\n'.join(decl_lines) if decl_lines else ''))
    h.append('#define NM_TAHOE_FWD(cls) NM_TAHOE_FWD_##cls')
    h += ['#define NM_TAHOE_FWD_DEFS \\'] + ['%s \\' % x for x in defs] + ['/* %d forwarded slots */' % n]
    h += ['#else', '#define NM_TAHOE_FWD(cls)', '#define NM_TAHOE_FWD_DEFS', '#endif']
    if miss - handled:
        raise ValueError('missing symbols not covered by a forwarding slot: ' + ', '.join(sorted(miss - handled)))
    # Keep the last valid header intact on parse, demangler or write failures.
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(mode='w', encoding='utf-8', newline='\n', dir=HERE, delete=False) as out:
            temporary = out.name
            out.write('\n'.join(h) + '\n')
        os.replace(temporary, os.path.join(HERE, 'tahoe_fwd.h'))
        temporary = None
    finally:
        if temporary is not None:
            os.unlink(temporary)
    print('tahoe_fwd.h: %d forwarded slots over %d base vtables' % (n, len(used)))
if __name__ == '__main__':
    try:
        if len(sys.argv) != 3:
            raise ValueError('usage: gen_tahoe_fwd.py NVACCEL_BINARY MISSING_SYMBOLS')
        main(sys.argv[1], sys.argv[2])
    except (OSError, ValueError) as exc:
        sys.exit('gen_tahoe_fwd: ' + str(exc))
